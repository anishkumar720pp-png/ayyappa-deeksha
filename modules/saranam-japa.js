window.SaranamJapaModule = (function () {
  let count = parseInt(localStorage.getItem("ayyappa_japa_count") || "0", 10);
  let malas = parseInt(localStorage.getItem("ayyappa_japa_malas") || "0", 10);

  function playBellChime() {
    try {
      const ctx = new (window.AudioContext || window.webkitAudioContext)();
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = "sine";
      osc.frequency.setValueAtTime(880, ctx.currentTime);
      osc.frequency.exponentialRampToValueAtTime(440, ctx.currentTime + 1.2);
      gain.gain.setValueAtTime(0.18, ctx.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 1.3);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start();
      osc.stop(ctx.currentTime + 1.3);
    } catch (e) {}
  }

  function render(lang) {
    const numEl = document.getElementById("japa-count-num");
    const mantraEl = document.getElementById("japa-mantra-text");
    const malasEl = document.getElementById("japa-malas-completed");
    if (!numEl) return;

    numEl.textContent = count;
    const idx = count % window.SARANAM_MANTRAS.length;
    mantraEl.textContent = window.SARANAM_MANTRAS[idx][lang] || window.SARANAM_MANTRAS[idx].en;

    const label = lang === "te" ? "పూర్తయిన మాలలు" : lang === "hi" ? "पूर्ण मालाएं" : "Malas Completed";
    malasEl.textContent = `${label}: ${malas}`;
  }

  function init(getLang) {
    const tapBtn = document.getElementById("japa-tap-btn");
    const resetBtn = document.getElementById("japa-reset-btn");

    tapBtn.addEventListener("click", () => {
      count += 1;
      if (navigator.vibrate) navigator.vibrate(25);
      if (count >= 108) {
        malas += 1;
        count = 0;
        playBellChime();
        if (navigator.vibrate) navigator.vibrate([80, 50, 120]);
      }
      localStorage.setItem("ayyappa_japa_count", String(count));
      localStorage.setItem("ayyappa_japa_malas", String(malas));
      render(getLang());
    });

    resetBtn.addEventListener("click", () => {
      count = 0;
      localStorage.setItem("ayyappa_japa_count", "0");
      render(getLang());
    });

    render(getLang());
  }

  return { init, render };
})();
